export function formatArtworkId(id: string): PresetArtworkId | undefined {
  return Object.hasOwn(FORMAT_ARTWORK, id)
    ? FORMAT_ARTWORK[id as keyof typeof FORMAT_ARTWORK]
    : undefined;
}

export interface PresetDescriptor {
  id: string;
  label: string;
  width: number;
  height: number;
  artworkId: string;
  animated?: boolean;
}

/** Home and Resize are distinct catalogs even where their IDs match. */
export function homePreset(format: Format): PresetDescriptor {
  return {
    id: format.id,
    label: format.label,
    width: format.width,
    height: format.height,
    artworkId: formatArtworkId(format.id) ?? "dimensions",
    ...(format.animated ? { animated: true } : {}),
  };
}

export function resizePreset(
  preset: ResizePreset,
  group: string,
): PresetDescriptor {
  return {
    id: preset.id,
    label: `${group} ${preset.label}`,
    width: preset.width,
    height: preset.height,
    artworkId: preset.id,
  };
}

/** Exact dimension-derived ratio, independent of editorial format subtitles. */
export function dimensionRatio(width: number, height: number): string {
  if (
    !Number.isSafeInteger(width) ||
    !Number.isSafeInteger(height) ||
    width <= 0 ||
    height <= 0
  )
    return "?";
  let a = width;
  let b = height;
  while (b !== 0) [a, b] = [b, a % b];
  return `${width / a}:${height / a}`;
}
